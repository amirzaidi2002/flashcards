function buildFlashcardSeeds(): FlashcardSeed[] {
  return deckSeeds.flatMap((deck) => {
    const words = WORDS_BY_DECK[deck.id] ?? []
    return words.map(([spanish, english], index) => ({
      id: `${deck.id}-${index + 1}`,
      spanish,
      english,
      deckId: deck.id,
    }))
  })
}

export const flashcardSeeds: FlashcardSeed[] = buildFlashcardSeeds()
